-- ============================================================================
-- ICONS · 신고 대상에 리뷰를 더한다 — enum 값 추가만 (#254)
--
-- Postgres는 같은 트랜잭션에서 방금 추가한 enum 값을 참조하지 못한다
-- (unsafe use of new value of enum type). Supabase CLI는 마이그레이션 파일
-- 하나를 한 트랜잭션으로 적용하므로, 값 추가와 그 값을 쓰는 함수 본문을 반드시
-- 다른 파일로 나눈다. 이 파일은 값 추가만 담고, 나머지는
-- 20260818130001_goods_reviews.sql이 담는다(20260818090000과 같은 이유·같은 형태).
--
-- 리뷰는 공개 UGC다. 공개되는 사용자 글에 신고 경로가 없으면 운영자는 문제 글을
-- 우연히 발견해야만 알 수 있다. 커뮤니티 포스트·댓글과 같은 큐에 넣어 같은 절차로
-- 처리한다 — 신고 큐를 도메인별로 쪼개면 어느 큐를 안 봤는지가 사고 원인이 된다.
--
-- `after 'comment'`로 위치를 지정한다. 사용자(user) 신고는 사람 대상이고
-- 포스트·댓글·리뷰는 글 대상이라, enum 순서를 "글 → 사람"으로 유지하면
-- enum_range를 그대로 화면 표시 순서로 쓸 수 있다.
-- ============================================================================

alter type public.report_target add value if not exists 'review' after 'comment';
