-- ---------------------------------------------------------------------------
-- 6. 마스킹과 알림 헬퍼
-- ---------------------------------------------------------------------------
-- 계좌번호는 뒤 4자리만 남긴다. 앞자리를 남기면 은행 코드와 지점이 드러난다.
create or replace function public.mask_refund_account_number(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_value is null then null
    when pg_catalog.length(pg_catalog.replace(p_value, '-', '')) <= 4
      then pg_catalog.repeat('*', 4)
    else pg_catalog.repeat('*', pg_catalog.length(pg_catalog.replace(p_value, '-', '')) - 4)
      || pg_catalog.right(pg_catalog.replace(p_value, '-', ''), 4)
  end;
$$;

create or replace function public.mask_refund_account_holder(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_value is null then null
    when pg_catalog.length(pg_catalog.btrim(p_value)) <= 1
      then pg_catalog.btrim(p_value)
    else pg_catalog.left(pg_catalog.btrim(p_value), 1)
      || pg_catalog.repeat('*', pg_catalog.length(pg_catalog.btrim(p_value)) - 1)
  end;
$$;

revoke all on function public.mask_refund_account_number(text)
  from public, anon, authenticated, service_role;
grant execute on function public.mask_refund_account_number(text) to service_role;

revoke all on function public.mask_refund_account_holder(text)
  from public, anon, authenticated, service_role;
