alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_reference_unique unique (reference);

alter table public.order_cancellation_requests
  add column claim_type text not null default 'cancel',
  add column stage text not null default 'requested',
  -- v1은 항상 null이다(주문 단위 전액 · 약관 제16조). 품목 단위 클레임(v2)으로
  -- 가는 문만 열어 둔다 — nullable이 아니면 v2에서 백필이 필요해진다.
  add column order_item_id uuid references public.order_items(id) on delete set null,
  add column hold_reason text,
  add column held_at timestamptz,
  -- 보류를 풀면 어디로 돌아가는가. 기억하지 않으면 재개가 항상 requested로
  -- 되감겨 이미 끝난 수거를 다시 시킨다.
  add column held_from text,
  add column collecting_at timestamptz,
  -- SLA의 기산점. 약관 제16조 "반환받은 날부터 3영업일"이 여기서 시작한다.
  -- stage가 processing으로 넘어가도 이 값은 남아 타이머가 계속 유효하다.
