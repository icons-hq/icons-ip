/*
 * 클레임 상태 변화 알림.
 *
 * dedupe_key는 stage가 아니라 이벤트로 나눈다. stage만 넣으면 한 단계에서 두 가지
 * 사건이 일어나는 경우 — 취소 승인(processing 진입)과 그 뒤의 환불 접수 — 뒤엣것이
 * 영구히 삼켜진다. 같은 사건의 재시도만 막으면 되므로 키는 이벤트 + 클레임 +
 * 그 전이의 updated_at이다. 보류/재개를 반복해도 매번 알림이 나가고, 같은 트랜잭션
 * 안에서 두 번 부르면 한 번만 남는다.
 */
create or replace function private.notify_order_claim(
  p_claim_id uuid,
  p_event text,
  p_title text,
  p_body text
)
returns void
language plpgsql
volatile
security definer
set search_path = ''
as $function$
declare
  v_claim public.order_cancellation_requests%rowtype;
begin
  select request.*
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id;

  if not found then
    return;
  end if;

  insert into public.notifications (
    user_id,
    type,
    title,
    body,
    link_path,
    source_type,
    source_id,
    dedupe_key
  )
  values (
    v_claim.requested_by,
    'claim_updated',
    p_title,
    p_body,
    '/orders/' || v_claim.order_id::text,
    'order_claim',
    v_claim.id::text,
    'claim:' || p_event || ':' || v_claim.id::text
      || ':' || pg_catalog.to_char(v_claim.updated_at, 'YYYYMMDDHH24MISSUS')
  )
  on conflict (user_id, dedupe_key) do nothing;
end;
