  add column reship_carrier text,
  add column reship_tracking_number text,
  add column reshipped_at timestamptz;

-- 컬럼 기본값('requested')은 이미 종결된 행에도 그대로 들어간다. 투영 CHECK를
-- 걸기 전에 기존 status를 stage로 옮긴다 — 순서를 뒤집으면 프리런치가 아닌
-- 환경에서 마이그레이션이 CHECK 위반으로 통째로 실패한다.
update public.order_cancellation_requests
set stage = status
where status <> 'requested';

alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_claim_type_check
  check (claim_type in ('cancel', 'return', 'exchange'));

alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_stage_check
  check (stage in (
    'requested',
    'in_review',
    'collecting',
    'collected',
    'on_hold',
    'processing',
    'needs_review',
    'completed',
    'rejected'
  ));

-- stage → status 투영. 이 제약이 "두 컬럼이지만 상태기계는 하나"를 강제한다.
-- 값을 만드는 곳은 private.order_claim_status_for_stage 하나뿐이고, 이 CHECK는
-- 그 함수를 우회한 쓰기를 거절하는 단언이다. 둘 다 고칠 일이 생기면 함수를 먼저
-- 고치고 여기를 맞춘다 — CHECK가 함수를 호출하게 만들면 그 함수에 대한 execute를
-- 모든 writer 롤에 열어야 해서 private 봉인이 무의미해진다.
alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_stage_projection_check
  check (
    case stage
      when 'processing' then status = 'processing'
      when 'needs_review' then status = 'needs_review'
      when 'completed' then status = 'completed'
      when 'rejected' then status = 'rejected'
      else status = 'requested'
    end
  );

alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_hold_reason_check
  check (
    hold_reason is null
    or (btrim(hold_reason) = hold_reason and length(hold_reason) between 10 and 200)
  );

-- 보류에는 사유가 반드시 있다. 사유 없는 보류는 구매자에게 설명할 수 없다.
alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_hold_reason_present_check
  check (stage <> 'on_hold' or hold_reason is not null);

-- 운송장 형식은 orders_tracking_number_check와 같다. 재출고도 같은 택배사
-- 레지스트리로 조회 URL을 만들므로 형식이 갈라지면 링크가 깨진다.
alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_reship_tracking_check
  check (
    reship_tracking_number is null
    or reship_tracking_number ~ '^[A-Z0-9]{8,30}$'
  );

-- 재출고 운송장은 택배사와 번호가 함께 있거나 함께 없다. 한쪽만 남으면
-- 배송 조회 링크를 만들 수 없다.
alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_reship_pair_check
  check ((reship_carrier is null) = (reship_tracking_number is null));

-- 재출고는 교환 전용이다. 반품·취소에 운송장이 붙으면 환불과 재출고가 동시에
-- 일어난 것처럼 보인다.
alter table public.order_cancellation_requests
  add constraint order_cancellation_requests_reship_type_check
  check (claim_type = 'exchange' or reship_tracking_number is null);

-- 주문당 활성 클레임 1건. 새 stage가 전부 status='requested'로 투영되므로
-- 기존 부분 인덱스 정의를 그대로 두어도 정확하다 — 정의를 다시 적어 의도를
-- 남기고, 나중에 status 목록을 손대는 사람이 이 주석을 보게 한다.
--   (수거 중인 반품이 있는데 취소 클레임이 또 접수되는 구멍을 막는다)

create index order_cancellation_requests_claim_queue_idx
  on public.order_cancellation_requests (claim_type, stage, requested_at desc);

/*
 * stage → status 투영의 단 하나의 구현.
 *
 * 절차 상태기계는 stage다. status는 그 파생값이며, 이 함수가 그 파생을 독점한다 —
 * RPC들이 각자 status를 계산하면 언젠가 하나가 틀리고(#252 F3의 resume이 그랬다)
 * 투영 CHECK가 그 경로를 통째로 막아 클레임이 어느 단계에서도 못 나가게 된다.
 * 그래서 새 RPC들은 stage만 쓰고 status는 아예 적지 않는다.
 */
create or replace function private.order_claim_status_for_stage(p_stage text)
returns text
language sql
immutable
set search_path = ''
as $function$
  select case p_stage
    when 'processing' then 'processing'
    when 'needs_review' then 'needs_review'
    when 'completed' then 'completed'
    when 'rejected' then 'rejected'
    else 'requested'
  end;
$function$;

revoke all on function private.order_claim_status_for_stage(text)
  from public, anon, authenticated, service_role;

/*
 * 레거시 writer가 status만 바꿔도 stage가 따라간다.
 *
 * admin_decide_order_cancellation · complete_order_cancellation_request ·
 * mark_order_cancellation_needs_review · admin_begin_order_cancellation_reconcile ·
 * finalize_goods_manual_payment_recovery는 전부 status만 쓴다. 이 트리거가 없으면
 * 그 함수들이 CHECK 위반으로 실패하거나(투영 불일치) 두 값이 갈라진다.
 *
 * 반대 방향(새 RPC)은 stage만 쓰고, 그 경우 status는 여기서 파생된다.
 */
create or replace function private.project_order_claim_stage()
returns trigger
language plpgsql
volatile
security definer
set search_path = ''
as $function$
begin
  -- INSERT: 레거시 경로는 status만 준다(예: 20260714190001의 needs_review 이관).
  -- stage는 컬럼 기본값 'requested'로 채워지므로 그대로 두면 투영 CHECK를 어긴다.
  -- 새 경로는 반대로 stage만 준다. 둘 다 명시한 INSERT는 손대지 않는다 — 그 조합이
  -- 틀렸다면 조용히 고치는 것보다 CHECK로 막히는 편이 낫다.
  if tg_op = 'INSERT' then
    if new.stage is not distinct from 'requested'
      and new.status is distinct from 'requested'
    then
      new.stage := new.status;
    elsif new.stage is distinct from 'requested'
      and new.status is not distinct from 'requested'
    then
      new.status := private.order_claim_status_for_stage(new.stage);
    end if;
    return new;
  end if;

  if new.stage is distinct from old.stage
    and new.status is not distinct from old.status
  then
    -- 절차가 움직였고 호출자는 status를 적지 않았다. 파생값은 여기서 만든다.
    new.status := private.order_claim_status_for_stage(new.stage);
  elsif new.status is distinct from old.status
    and new.stage is not distinct from old.stage
  then
    -- 레거시 writer. status에서 stage를 되돌린다 — requested로 감는 경로(정합화
    -- 재시도)는 절차를 처음으로 감지 않고 이미 지난 단계를 보존한다.
    new.stage := case
      when new.status in ('processing', 'needs_review', 'completed', 'rejected')
        then new.status
      when old.stage in ('in_review', 'collecting', 'collected', 'on_hold')
        then old.stage
      else 'requested'
    end;
    new.status := private.order_claim_status_for_stage(new.stage);
  end if;

  -- 둘 다 바꾼 UPDATE는 그대로 통과시킨다. 일치하면 CHECK가 받고, 어긋나면 막는다.
  return new;
end;
$function$;

create trigger trg_order_cancellation_requests_stage_projection
before insert or update on public.order_cancellation_requests
for each row execute function private.project_order_claim_stage();

revoke all on function private.project_order_claim_stage()
  from public, anon, authenticated, service_role;

-- 새 컬럼 중 구매자가 읽어도 되는 것만 컬럼 grant에 더한다. hold_reason은
-- 알림 본문으로 전달하고 원문 열람은 열지 않는다 — 운영 메모가 그대로 노출되면
-- 내부 판단 근거가 새어 나간다.
grant select (
  reference,
  claim_type,
  stage,
  collecting_at,
  collected_at,
  reship_carrier,
  reship_tracking_number,
  reshipped_at
) on table public.order_cancellation_requests to authenticated;

-- ---------------------------------------------------------------------------
-- 3. 환불계좌 — service_role 전용 격리
-- ---------------------------------------------------------------------------
-- public 스키마에 두지 않는다. private은 Data API에 노출되지 않으므로 RLS가
-- 뚫려도 브라우저가 이 테이블에 닿을 수 없다(payment_provider_evidence 선례).
create table private.claim_refund_accounts (
  claim_id uuid primary key
    references public.order_cancellation_requests(id) on delete cascade,
  bank_name text,
  account_number text,
  account_holder text,
  -- 마스킹은 저장 시점에 만든다. 화면이 원문을 읽어 가공하면 원문이 앱 메모리와
  -- 로그를 거치게 된다. 파기 후에도 이 값은 남아 "무엇을 받았었는지"를 말한다.
  masked_account text not null,
  masked_holder text not null,
  created_at timestamptz not null default now(),
  purge_after timestamptz,
  purged_at timestamptz,
  constraint claim_refund_accounts_bank_name_check check (
    bank_name is null
    or (btrim(bank_name) = bank_name and length(bank_name) between 1 and 40)
  ),
  constraint claim_refund_accounts_account_number_check check (
    account_number is null
    or account_number ~ '^[0-9-]{8,30}$'
  ),
  constraint claim_refund_accounts_account_holder_check check (
    account_holder is null
    or (btrim(account_holder) = account_holder and length(account_holder) between 1 and 40)
  ),
  -- 파기된 행은 원문 세 칸이 모두 비어야 한다. 하나라도 남으면 파기가 아니다.
  constraint claim_refund_accounts_purge_complete_check check (
    purged_at is null
    or (bank_name is null and account_number is null and account_holder is null)
  )
);

create index claim_refund_accounts_purge_idx
  on private.claim_refund_accounts (purge_after)
  where purged_at is null and purge_after is not null;

alter table private.claim_refund_accounts enable row level security;
revoke all on table private.claim_refund_accounts
  from public, anon, authenticated, service_role;
grant select, insert, update on table private.claim_refund_accounts to service_role;

/*
 * 파기 기한은 "클레임이 끝났다"는 사실 하나에서 잡힌다.
 *
 * 환불 완료 기록(admin_record_order_claim_refund)에서만 잡으면 거절로 끝난 건과
 * 레거시 정합화 경로로 completed가 된 건의 계좌 원문이 purge_after = null로 남고,
 * 파기 잡의 부분 인덱스(`where purged_at is null and purge_after is not null`)가
 * 그 행을 아예 보지 않아 원문이 무기한 남는다. 종결 stage에 도달하는 경로가
 * 여럿(새 RPC · 레거시 status 쓰기 · 교환 재출고)이므로 판정은 테이블 하나가
 * 한다 — 경로마다 적으면 언젠가 하나가 빠진다.
 */
create or replace function private.seal_order_claim_refund_account()
returns trigger
language plpgsql
volatile
security definer
set search_path = ''
as $function$
begin
  if new.stage in ('completed', 'rejected')
    and (tg_op = 'INSERT' or old.stage is distinct from new.stage)
  then
    update private.claim_refund_accounts as account
    set purge_after = coalesce(
      account.purge_after,
      pg_catalog.now() + '30 days'::interval
    )
    where account.claim_id = new.id
      and account.purged_at is null;
  end if;

  return null;
end;
$function$;

create trigger trg_order_cancellation_requests_seal_refund_account
after insert or update on public.order_cancellation_requests
for each row execute function private.seal_order_claim_refund_account();

revoke all on function private.seal_order_claim_refund_account()
  from public, anon, authenticated, service_role;

