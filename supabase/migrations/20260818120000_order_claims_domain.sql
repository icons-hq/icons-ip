-- ICONS · 클레임 도메인(취소·반품·교환)과 수단별 환불 실행 (#252)
--
-- 지금까지 있던 것은 "청약철회(취소)" 하나뿐이었다. 교환은 개념이 없었고 반품
-- 입고 확인은 승인 버튼에 암묵적으로 흡수돼 있었다(#176 D11). 스마트스토어의
-- 취소·반품·교환 3화면과 절차(요청→수거→입고→처리)를 카피하되, 주문 단위 전액
-- 원칙(약관 제16조)은 그대로 둔다.
--
-- ## 테이블을 새로 만들지 않는 이유
--
-- order_cancellation_requests를 rename하거나 새 테이블로 쪼개면, 이 테이블을
-- 본문 텍스트로 참조하는 함수 10여 개(request/decide/finalize/complete/
-- needs_review/manual recovery/account deletion/settle/dispatch 게이트)를 전부
-- 재생성해야 한다. 프리런치라 데이터는 비어 있어도 그 재생성 자체가 이번 변경의
-- 가장 큰 위험이다. 테이블명을 유지하고 컬럼을 넓힌다.
--
-- ## status와 stage — 왜 두 컬럼인가
--
-- 새 상태(in_review·collecting·collected·on_hold)를 status CHECK에 그냥 넣으면
-- 기존 게이트 12곳이 조용히 뚫린다. 그것들은 전부
-- `status in ('requested','processing','needs_review')` 리터럴로 "활성 요청"을
-- 판정한다 — admin_update_order_status(배송 전이 차단),
-- cancel_order_with_provider_evidence(웹훅 즉시취소 차단),
-- settle_delivered_orders(자동 거래확정 차단),
-- private.account_deletion_blockers(탈퇴 차단),
-- request_order_cancellation(중복 접수 차단), 부분 unique 인덱스(주문당 1건).
-- collecting 상태의 반품 클레임이 그 리터럴에 걸리지 않으면, 회수 중인 주문을
-- 어드민이 발송하고 웹훅이 취소하고 잡이 거래확정한다.
--
-- 그래서 절차 상태기계는 `stage`에 두고, `status`는 그 기계의 **레거시 투영**으로
-- 남긴다. 두 개의 상태기계가 아니라 하나의 기계와 하나의 파생값이다 —
-- 아래 CHECK가 불일치를 금지하고, 트리거가 레거시 writer의 status 변경을 stage로
-- 자동 승격한다(그래서 기존 함수를 한 줄도 고치지 않아도 두 값이 갈라지지 않는다).
--
-- 투영을 계산하는 곳은 private.order_claim_status_for_stage 하나다. 새 RPC들은
-- stage만 쓰고 status는 적지 않는다 — 전이마다 status를 손으로 계산하면 하나가
-- 틀리는 순간 그 전이가 CHECK에 막혀 클레임이 어느 단계에서도 못 나간다.
--
--   stage                      →  status (레거시 투영)
--   ------------------------------------------------------
--   requested                  →  requested   (접수)
--   in_review                  →  requested   (검토 중)
--   collecting                 →  requested   (수거 중)
--   collected                  →  requested   (입고 확인)
--   on_hold                    →  requested   (운영 보류 — 재개 가능)
--   processing                 →  processing  (환불/재출고 실행 중)
--   needs_review               →  needs_review(provider 정합화 실패)
--   completed                  →  completed
--   rejected                   →  rejected
--
-- needs_review와 on_hold는 다른 개념이다. needs_review는 결제사 원장과 로컬 장부가
-- 어긋나 자동 정합화가 실패한 상태(기계가 푼다)이고, on_hold는 반품 배송비 미정산·
-- 연락 두절처럼 사람이 판단할 운영 보류다. 합치면 자동 복구 대상 큐와 사람 판단
-- 큐가 섞인다.
--
-- ## 환불계좌 보관 — #208 미응답에 대한 안전 기본값
--
-- questionnaire #208("환불계좌 암호화·보관기간")은 아직 답이 없다. 답을 기다리며
-- 수집을 미루면 무통장 환불 경로 자체가 없으므로, 가장 보수적인 가정으로 먼저
-- 만들고 답이 오면 좁힌다:
--   · 원문은 private 스키마의 별도 테이블에만 둔다(service_role 전용, staff 읽기
--     표면 없음). public 조인 대상이 아니므로 실수로 목록에 섞일 수 없다.
--   · 화면에는 마스킹 값만 나간다. 마스킹은 저장 시점에 만들어 원문 없이도 읽힌다.
--   · 클레임이 종결(completed·rejected)되면 30일 뒤 원문을 파기한다
--     (seal_order_claim_refund_account → purge_expired_claim_refund_accounts).
--     기준은 "환불이 완료됐는가"가 아니라 "클레임이 끝났는가"다 — 거절로 끝난 건도
--     송금할 계좌가 더는 필요 없고, 완료 기록을 남기지 않는 레거시 정합화 경로로
--     끝난 건도 마찬가지다. 30일은 카드사·은행 재확인 요청이 들어올 수 있는 실무
--     창을 최소로 잡은 값이며, #208의 답이 더 짧은 기간을 정하면 그 값으로 줄인다.
--   · 교환에는 계좌를 저장하지 않는다. 재출고로 끝나므로 돈이 돌아갈 경로가 없고,
--     목적 없는 수집은 보관 기간을 아무리 짧게 잡아도 정당화되지 않는다.
-- 이 가정은 #208 코멘트에도 남긴다.
--
-- ## 재고 복원과 카드팩 회수는 여기서 하지 않는다
--
-- 그 두 부수효과는 finalize_order_cancellation_with_provider_evidence 한 곳에만
-- 있다. 클레임 완료는 기존 정합화 경로(legacy Toss = 오케스트레이터, Korpay =
-- finalize_goods_manual_payment_recovery)를 그대로 타고, 그 경로가 요청을
-- completed로 닫는다. 이 파일의 환불 원장 RPC는 "완료" 기록을 클레임이 이미
-- completed일 때만 허용한다 — 돈이 돌아갔다고 적으면서 재고가 안 돌아오는 조합을
-- DB가 거절한다.
