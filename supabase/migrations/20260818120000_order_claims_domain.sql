-- ---------------------------------------------------------------------------
-- 7. 운영자 결정 — 승인·거부·보류·재개
-- ---------------------------------------------------------------------------
create or replace function public.admin_decide_order_claim(
  p_claim_id uuid,
  p_decision text,
  p_note text
)
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := (select auth.uid());
  v_order_id uuid;
  v_order_status public.order_status;
  v_delivered_at timestamptz;
  v_claim record;
  v_next_stage text;
  v_payment_count integer;
  /*
   * 보류를 벗긴 실질 단계.
   *
   * on_hold는 절차의 단계가 아니라 그 위에 덮인 표시다. 보류 중인 클레임을
   * 판정할 때 stage만 보면 processing에서 건 보류가 "아직 착수 전"으로 보인다.
   * lib/orders/claims.ts의 orderClaimEffectiveStage와 같은 정의다.
   */
  v_effective_stage text;
begin
  if v_actor is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if p_decision not in ('review', 'approve', 'reject', 'hold', 'resume') then
    raise check_violation using message = 'invalid claim decision';
  end if;

  select request.order_id
  into v_order_id
  from public.order_cancellation_requests as request
  where request.id = p_claim_id;

  if v_order_id is null then
    raise no_data_found using message = 'claim_not_found';
  end if;

  -- 잠금 순서: 주문 → 클레임. admin_decide_order_cancellation과 같다.
  select orders.status, orders.delivered_at
  into v_order_status, v_delivered_at
  from public.orders
  where orders.id = v_order_id
  for update;

  select request.*
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id
  for update;

  if v_claim.stage in ('completed', 'rejected') then
    raise exception using message = 'claim_not_decidable';
  end if;

  v_effective_stage := case
    when v_claim.stage = 'on_hold' then coalesce(v_claim.held_from, 'requested')
    else v_claim.stage
  end;

  if p_decision = 'reject' then
    if p_note is null
      or btrim(p_note) <> p_note
      or length(p_note) not between 10 and 200
    then
      raise check_violation using message = 'invalid rejection reason';
    end if;

    /*
     * 거절은 처리에 착수하기 전에만 가능하다.
     *
     * processing·needs_review는 이미 durable claim과 refunds(status='requested')를
     * 열어 둔 상태다. 그 상태에서 요청만 rejected로 닫으면 주문은 "취소 진행 중"인
     * 채로 남고 complete_order_cancellation_request가 cancellation_request_not_processing
     * 으로 막아 돈이 갇힌다. needs_review는 Korpay 수동 복구 seam까지 함께 닫혀
     * 복구 경로가 하나도 남지 않는다. 그 단계에서 되돌릴 일이 있으면 거절이 아니라
     * 보류·정합화로 처리한다.
     */
    if v_effective_stage not in ('requested', 'in_review', 'collecting', 'collected') then
      raise exception using message = 'claim_not_rejectable';
    end if;

    update public.order_cancellation_requests
    set
      stage = 'rejected',
      decided_by = v_actor,
      decision_note = p_note,
      decided_at = now(),
      updated_at = now()
    where id = p_claim_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.claim_rejected',
      'order:' || v_order_id::text,
      jsonb_build_object(
        'claimId', p_claim_id,
        'claimType', v_claim.claim_type,
        'from', v_claim.stage,
        'to', 'rejected',
        'reason', p_note
      )
    );

    perform private.notify_order_claim(
      p_claim_id,
      'rejected',
      '클레임 요청이 거절됐어요',
      '요청이 거절됐습니다. 사유: ' || p_note
    );
    return 'rejected';
  end if;

  if p_decision = 'hold' then
    if p_note is null
      or btrim(p_note) <> p_note
      or length(p_note) not between 10 and 200
    then
      raise check_violation using message = 'invalid hold reason';
    end if;
    if v_claim.stage = 'on_hold' then
      return 'on_hold';
    end if;

    update public.order_cancellation_requests
    set
      stage = 'on_hold',
      held_from = v_claim.stage,
      hold_reason = p_note,
      held_at = now(),
      updated_at = now()
    where id = p_claim_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.claim_held',
      'order:' || v_order_id::text,
      jsonb_build_object(
        'claimId', p_claim_id,
        'claimType', v_claim.claim_type,
        'from', v_claim.stage,
        'to', 'on_hold',
        'reason', p_note
      )
    );

    perform private.notify_order_claim(
      p_claim_id,
      'held',
      '클레임 처리가 보류됐어요',
      '처리가 보류됐습니다. 사유: ' || p_note
    );
    return 'on_hold';
  end if;

  if p_decision = 'resume' then
    if v_claim.stage <> 'on_hold' then
      raise exception using message = 'claim_not_held';
    end if;

    v_next_stage := coalesce(v_claim.held_from, 'requested');

    -- status를 여기서 계산하지 않는다. held_from이 needs_review면 이 자리에서
    -- 'requested'를 적어 투영 CHECK에 막혔고, 보류가 영원히 풀리지 않았다(F3).
    update public.order_cancellation_requests
    set
      stage = v_next_stage,
      held_from = null,
      hold_reason = null,
      held_at = null,
      updated_at = now()
    where id = p_claim_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.claim_resumed',
      'order:' || v_order_id::text,
      jsonb_build_object(
        'claimId', p_claim_id,
        'claimType', v_claim.claim_type,
        'from', 'on_hold',
        'to', v_next_stage
      )
    );

    perform private.notify_order_claim(
      p_claim_id,
      'resumed',
      '클레임 처리가 재개됐어요',
      '보류가 해제되어 처리가 다시 시작됐습니다.'
    );
    return v_next_stage;
  end if;

  if p_decision = 'review' then
    if v_claim.stage <> 'requested' then
      raise exception using message = 'claim_not_decidable';
    end if;

    update public.order_cancellation_requests
    set
      stage = 'in_review',
      decided_by = v_actor,
      updated_at = now()
    where id = p_claim_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.claim_in_review',
      'order:' || v_order_id::text,
      jsonb_build_object(
        'claimId', p_claim_id,
        'claimType', v_claim.claim_type,
        'from', 'requested',
        'to', 'in_review'
      )
    );
    return 'in_review';
  end if;

  -- 승인.
  if v_claim.stage not in ('requested', 'in_review') then
    raise exception using message = 'claim_not_decidable';
  end if;

  if v_order_status not in (
    'pending', 'paid', 'confirmed', 'shipping', 'delivered', 'done'
  ) then
    raise exception using message = 'order_not_cancelable';
  end if;

  -- 돈이 걸린 판정은 승인 단계에서 다시 본다(#189). 기준 시각은 접수 시각이다.
  if public.order_withdrawal_deadline_passed(
    v_delivered_at,
    v_claim.reason_type,
    v_claim.requested_at
  ) then
    raise check_violation using message = 'withdrawal_deadline_expired';
  end if;

  -- 취소는 회수할 물건이 없으므로 곧장 환불 처리로 간다. 반품·교환은 수거부터다.
  if v_claim.claim_type = 'cancel' then
    v_next_stage := 'processing';
  else
    v_next_stage := 'collecting';
  end if;

  if v_next_stage = 'processing' then
    insert into public.order_cancellation_claims (
      order_id,
      requested_by,
      previous_status
    )
    values (v_order_id, v_claim.requested_by, v_order_status)
    on conflict (order_id) do nothing;

    insert into public.refunds (
      payment_id,
      amount,
      reason,
      status,
      cancellation_request_id
    )
    select
      payment.id,
      payment.amount,
      v_claim.reason,
      case when refund.status = 'done' then 'done' else 'requested' end,
      p_claim_id
    from public.payments as payment
    left join public.refunds as refund on refund.payment_id = payment.id
    where payment.purpose = 'order'
      and payment.ref_id = v_order_id
      and payment.status in ('pending', 'paid', 'canceled', 'refunded')
    on conflict (payment_id) do update
    set
      cancellation_request_id = excluded.cancellation_request_id,
      reason = coalesce(public.refunds.reason, excluded.reason),
      status = case
        when public.refunds.status = 'done' then 'done'
        else 'requested'
      end;

    select count(*)::integer
    into v_payment_count
    from public.payments as payment
    where payment.purpose = 'order'
      and payment.ref_id = v_order_id
      and payment.status in ('pending', 'paid', 'canceled', 'refunded');
  end if;

  update public.order_cancellation_requests
  set
    stage = v_next_stage,
    decided_by = v_actor,
    decision_note = null,
    decided_at = now(),
    provider_started_at = case when v_next_stage = 'processing' then now() else provider_started_at end,
    collecting_at = case when v_next_stage = 'collecting' then now() else collecting_at end,
    updated_at = now()
  where id = p_claim_id;

  insert into public.audit_log (actor_id, action, target, diff)
  values (
    v_actor,
    'admin.order.claim_approved',
    'order:' || v_order_id::text,
    jsonb_build_object(
      'claimId', p_claim_id,
      'claimType', v_claim.claim_type,
      'from', v_claim.stage,
      'to', v_next_stage,
      'previousOrderStatus', v_order_status::text,
      'reasonType', v_claim.reason_type,
      'paymentCount', coalesce(v_payment_count, 0)
    )
  );

  perform private.notify_order_claim(
    p_claim_id,
    'approved',
    '클레임 요청이 승인됐어요',
    case
      when v_next_stage = 'collecting'
        then '요청이 승인됐습니다. 안내받은 방법으로 굿즈를 반송해주세요.'
      else '요청이 승인됐습니다. 결제 취소 처리를 시작합니다.'
    end
  );

  return v_next_stage;
end;
$$;

revoke all on function public.admin_decide_order_claim(uuid, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.admin_decide_order_claim(uuid, text, text)
  to authenticated;

/*
 * 레거시 주문 콘솔의 승인·거절은 "접수 단계의 취소"만 소유한다.
 *
 * 이 함수는 활성 요청을 status로 판정했다(`status <> 'requested'`면 거절). 새
 * stage — in_review · collecting · collected · on_hold — 는 전부
 * status='requested'로 투영되므로, 그 판정에는 수거 중인 반품과 입고까지 끝난
 * 교환과 보류 중인 클레임이 전부 "결정 가능"으로 보인다. 승인하면 무슨 일이
 * 벌어지는가:
 *
 *   반품(collecting) → durable claim + 환불 intent 생성 → 정합화가 주문을 취소하고
 *     재고를 복원하고 미개봉 카드팩을 회수한다. 굿즈는 아직 고객에게 있다.
 *     D11이 명시 상태로 승격한 "입고 확인"이 통째로 건너뛰어진다.
 *   교환(collected) → refunds 행이 생긴다. "교환에는 환불이 없다"가 깨진다.
 *   보류(on_hold)  → 보류가 조용히 사라지고 hold_reason만 유령으로 남는다.
 *
 * 그래서 판정을 status가 아니라 절차 상태기계(stage)에서 한다. 나머지는 전부
 * 클레임 콘솔(admin_decide_order_claim)의 몫이다.
 *
 * 20260818090001의 정의를 그대로 옮기고 이 전제조건만 더한다.
 */
create or replace function public.admin_decide_order_cancellation(
  p_request_id uuid,
  p_decision text,
  p_note text
)
returns void
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := (select auth.uid());
  v_order_id uuid;
  v_order_status public.order_status;
  v_delivered_at timestamptz;
  v_request record;
  v_payment_count integer;
begin
  if v_actor is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if p_decision not in ('approve', 'reject') then
    raise check_violation using message = 'invalid cancellation decision';
  end if;

  select request.order_id
  into v_order_id
  from public.order_cancellation_requests as request
  where request.id = p_request_id;

  if v_order_id is null then
    raise no_data_found using message = 'cancellation_request_not_found';
  end if;

  select orders.status, orders.delivered_at
  into v_order_status, v_delivered_at
  from public.orders
  where orders.id = v_order_id
  for update;

  select request.*
  into v_request
  from public.order_cancellation_requests as request
  where request.id = p_request_id
  for update;

  if v_request.status <> 'requested' then
    raise exception using message = 'cancellation_request_not_decidable';
  end if;

  -- status만으로는 부족하다. 새 stage는 전부 'requested'로 투영된다.
  if v_request.claim_type <> 'cancel' or v_request.stage <> 'requested' then
    raise exception using message = 'claim_requires_claim_console';
  end if;

  if v_order_status not in (
    'pending', 'paid', 'confirmed', 'shipping', 'delivered', 'done'
  ) then
    raise exception using message = 'order_not_cancelable';
  end if;

  if p_decision = 'reject' then
    if p_note is null
      or btrim(p_note) <> p_note
      or length(p_note) not between 10 and 200
    then
      raise check_violation using message = 'invalid rejection reason';
    end if;

    update public.order_cancellation_requests
    set
      status = 'rejected',
      decided_by = v_actor,
      decision_note = p_note,
      decided_at = now(),
      updated_at = now()
    where id = p_request_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.cancellation_rejected',
      'order:' || v_order_id::text,
      jsonb_build_object(
        'requestId', p_request_id,
        'from', 'requested',
        'to', 'rejected',
        'reason', p_note
      )
    );
    return;
  end if;

  if public.order_withdrawal_deadline_passed(
    v_delivered_at,
    v_request.reason_type,
    v_request.requested_at
  ) then
    raise check_violation using message = 'withdrawal_deadline_expired';
  end if;

  insert into public.order_cancellation_claims (
    order_id,
    requested_by,
    previous_status
  )
  values (
    v_order_id,
    v_request.requested_by,
    v_order_status
  )
  on conflict (order_id) do nothing;

  insert into public.refunds (
    payment_id,
    amount,
    reason,
    status,
    cancellation_request_id
  )
  select
    payment.id,
    payment.amount,
    v_request.reason,
    case when refund.status = 'done' then 'done' else 'requested' end,
    p_request_id
  from public.payments as payment
  left join public.refunds as refund on refund.payment_id = payment.id
  where payment.purpose = 'order'
    and payment.ref_id = v_order_id
    and payment.status in ('pending', 'paid', 'canceled', 'refunded')
  on conflict (payment_id) do update
  set
    cancellation_request_id = excluded.cancellation_request_id,
    reason = coalesce(public.refunds.reason, excluded.reason),
    status = case
      when public.refunds.status = 'done' then 'done'
      else 'requested'
    end;

  select count(*)::integer
  into v_payment_count
  from public.payments as payment
  where payment.purpose = 'order'
    and payment.ref_id = v_order_id
    and payment.status in ('pending', 'paid', 'canceled', 'refunded');

  update public.order_cancellation_requests
  set
    status = 'processing',
    decided_by = v_actor,
    decision_note = null,
    decided_at = now(),
    provider_started_at = now(),
    updated_at = now()
  where id = p_request_id;

  insert into public.audit_log (actor_id, action, target, diff)
  values (
    v_actor,
    'admin.order.cancellation_approved',
    'order:' || v_order_id::text,
    jsonb_build_object(
      'requestId', p_request_id,
      'from', 'requested',
      'to', 'processing',
      'previousOrderStatus', v_order_status::text,
      'reasonType', v_request.reason_type,
      'paymentCount', v_payment_count
    )
  );
end;
$$;

revoke all on function public.admin_decide_order_cancellation(uuid, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.admin_decide_order_cancellation(uuid, text, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- 13. 주문 콘솔에 클레임 유형·단계를 싣는다
-- ---------------------------------------------------------------------------
/*
 * 주문 콘솔이 "청약철회 요청 · 요청 접수"만 그리면 수거 중인 반품도 그렇게 보인다.
 * 위 게이트가 그 승인을 거절하더라도, 버튼이 그려져 있는 한 운영자는 누른다 —
 * 그리고 실패 문구로 상황을 배운다. 콘솔이 claim_type과 stage를 함께 읽어야
 * 애초에 그 버튼을 그리지 않고 클레임 콘솔로 보낼 수 있다.
 *
 * 반환 컬럼이 늘어 시그니처가 바뀌므로 drop 후 재생성한다(20260818100001 선례).
 */
drop function if exists public.admin_search_orders(
  text, date, date, text, integer, integer, timestamptz
);

create or replace function public.admin_search_orders(
  p_status text default null,
  p_from date default null,
  p_to date default null,
  p_query text default null,
  p_limit integer default 20,
  p_offset integer default 0,
  p_confirmed_before timestamptz default null
)
returns table (
  id uuid,
  user_id uuid,
  buyer_name text,
  buyer_email text,
  status public.order_status,
  total bigint,
  address jsonb,
  created_at timestamptz,
  updated_at timestamptz,
  shipping_carrier text,
  tracking_number text,
  confirmed_at timestamptz,
  shipped_at timestamptz,
  delivered_at timestamptz,
  done_at timestamptz,
  cancellation_request_id uuid,
  cancellation_request_status text,
  cancellation_reason_type text,
  cancellation_requested_at timestamptz,
  cancellation_decided_at timestamptz,
  cancellation_decision_note text,
  cancellation_claim_type text,
  cancellation_stage text,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_query text := nullif(btrim(coalesce(p_query, '')), '');
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 100);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
begin
  if (select auth.uid()) is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if p_status is not null
    and not exists (
      select 1
      from unnest(enum_range(null::public.order_status)) as allowed(value)
      where allowed.value::text = p_status
    )
  then
    raise check_violation using message = 'invalid order status filter';
  end if;

  if p_from is not null and p_to is not null and p_from > p_to then
    raise check_violation using message = 'invalid order date range';
  end if;

  if v_query is not null and length(v_query) > 100 then
    raise check_violation using message = 'order search query too long';
  end if;

  return query
  select
    orders.id,
    orders.user_id,
    profile.nickname as buyer_name,
    profile.email as buyer_email,
    orders.status,
    orders.total,
    orders.address,
    orders.created_at,
    orders.updated_at,
    orders.shipping_carrier,
    orders.tracking_number,
    orders.confirmed_at,
    orders.shipped_at,
    orders.delivered_at,
    orders.done_at,
    cancellation.id as cancellation_request_id,
    cancellation.status as cancellation_request_status,
    cancellation.reason_type as cancellation_reason_type,
    cancellation.requested_at as cancellation_requested_at,
    cancellation.decided_at as cancellation_decided_at,
    cancellation.decision_note as cancellation_decision_note,
    cancellation.claim_type as cancellation_claim_type,
    cancellation.stage as cancellation_stage,
    count(*) over()::bigint as total_count
  from public.orders as orders
  join public.profiles as profile on profile.id = orders.user_id
  left join lateral (
    select
      request.id,
      request.status,
      request.reason_type,
      request.requested_at,
      request.decided_at,
      request.decision_note,
      request.claim_type,
      request.stage
    from public.order_cancellation_requests as request
    where request.order_id = orders.id
    order by request.requested_at desc, request.id desc
    limit 1
  ) as cancellation on true
  where (p_status is null or orders.status::text = p_status)
    and (
      p_from is null
      or orders.created_at >= (p_from::timestamp at time zone 'Asia/Seoul')
    )
    and (
      p_to is null
      or orders.created_at < ((p_to + 1)::timestamp at time zone 'Asia/Seoul')
    )
    -- 발주확인 기록이 없는 주문은 지연 목록에 넣지 않는다. confirmed_at이 비어
    -- 있다는 것은 사다리 도입 전 행이라는 뜻이고, 없는 기산점으로 "지연"이라고
    -- 부르면 운영자가 실제로 늦은 주문을 못 찾는다.
    and (p_confirmed_before is null or orders.confirmed_at < p_confirmed_before)
    and (
      v_query is null
      or position(lower(v_query) in lower(orders.id::text)) > 0
      or position(lower(v_query) in lower(coalesce(profile.email, ''))) > 0
      or position(lower(v_query) in lower(coalesce(profile.nickname, ''))) > 0
    )
  order by orders.created_at desc, orders.id desc
  limit v_limit
  offset v_offset;
end;
$$;

revoke all on function public.admin_search_orders(
  text, date, date, text, integer, integer, timestamptz
) from public, anon, authenticated, service_role;
grant execute on function public.admin_search_orders(
  text, date, date, text, integer, integer, timestamptz
) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. 수거·입고 확인
-- ---------------------------------------------------------------------------
-- D11("입고 확인은 승인에 내포")을 명시 상태로 승격한다. 반품·교환에서
-- "물건이 창고에 도착했는가"는 환불·재출고를 여는 사실이고, 승인 버튼 하나에
-- 접혀 있으면 그 사실이 어디에도 기록되지 않는다.
create or replace function public.admin_record_order_claim_collection(
  p_claim_id uuid,
  p_stage text
)
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := (select auth.uid());
  v_claim record;
begin
  if v_actor is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if p_stage not in ('collecting', 'collected') then
    raise check_violation using message = 'invalid collection stage';
  end if;

  select request.*
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id
  for update;

  if not found then
    raise no_data_found using message = 'claim_not_found';
  end if;

  if v_claim.claim_type = 'cancel' then
    raise exception using message = 'claim_type_has_no_collection';
  end if;

  -- 수거 시작은 승인이 이미 만든다. 같은 값으로 다시 부르면 멱등하게 통과하고,
  -- 그 밖의 단계에서 부르면 거절한다 — 뒤로 감는 전이를 만들지 않는다.
  if p_stage = 'collecting' then
    if v_claim.stage = 'collecting' then
      return 'collecting';
    end if;
    raise exception using message = 'claim_not_collectable';
  end if;

  if v_claim.stage = 'collected' then
    return 'collected';
  end if;
  if v_claim.stage <> 'collecting' then
    raise exception using message = 'claim_not_collectable';
  end if;

  update public.order_cancellation_requests
  set
    stage = p_stage,
    collected_at = case when p_stage = 'collected' then now() else collected_at end,
    updated_at = now()
  where id = p_claim_id;

  insert into public.audit_log (actor_id, action, target, diff)
  values (
    v_actor,
    'admin.order.claim_collected',
    'order:' || v_claim.order_id::text,
    jsonb_build_object(
      'claimId', p_claim_id,
      'claimType', v_claim.claim_type,
      'from', v_claim.stage,
      'to', p_stage
    )
  );

  perform private.notify_order_claim(
    p_claim_id,
    'collected',
    '반송한 굿즈가 입고됐어요',
    case
      when v_claim.claim_type = 'exchange'
        then '입고가 확인됐습니다. 교환 상품 재출고를 준비합니다.'
      else '입고가 확인됐습니다. 영업일 기준 3일 이내에 환급 절차를 진행합니다.'
    end
  );

  return p_stage;
end;
$$;

revoke all on function public.admin_record_order_claim_collection(uuid, text)
  from public, anon, authenticated, service_role;
grant execute on function public.admin_record_order_claim_collection(uuid, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- 9. 환불 원장 — 접수와 완료
-- ---------------------------------------------------------------------------
/*
 * 이 함수는 돈을 움직이지 않는다. 원장에 "어떤 수단으로 누가 언제 접수했는가"를
 * 적을 뿐이다.
 *
 * `filed`(접수): 반품은 입고 확인(collected) 뒤에만, 취소는 승인 뒤(processing)에
 *   부를 수 있다. 반품의 경우 여기서 durable claim과 환불 intent가 생긴다 —
 *   D11이 말한 "물건을 받은 뒤 승인한다"가 실제로 일어나는 지점이다.
 *
 * `completed`(완료): 클레임이 이미 completed일 때만 허용한다. completed는
 *   finalize_order_cancellation_with_provider_evidence를 지난 경로(legacy Toss
 *   오케스트레이터 · Korpay finalize_goods_manual_payment_recovery)만 만들 수
 *   있으므로, 재고 복원과 카드팩 회수 없이 "환불 완료"가 기록되는 조합이
 *   DB에서 불가능해진다.
 */
create or replace function public.admin_record_order_claim_refund(
  p_claim_id uuid,
  p_method text,
  p_stage text,
  p_note text default null
)
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := (select auth.uid());
  v_claim record;
  v_order_status public.order_status;
  v_refund_count integer;
begin
  if v_actor is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if p_method not in ('pg_cancel', 'bank_transfer') then
    raise check_violation using message = 'invalid refund method';
  end if;
  if p_stage not in ('filed', 'completed') then
    raise check_violation using message = 'invalid refund stage';
  end if;
  if p_note is not null
    and (btrim(p_note) <> p_note or length(p_note) not between 1 and 300)
  then
    raise check_violation using message = 'invalid settlement note';
  end if;

  select request.order_id
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id;

  if not found then
    raise no_data_found using message = 'claim_not_found';
  end if;

  select orders.status
  into v_order_status
  from public.orders
  where orders.id = v_claim.order_id
  for update;

  select request.*
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id
  for update;

  if v_claim.claim_type = 'exchange' then
    raise exception using message = 'exchange_has_no_refund';
  end if;

  /*
   * 계좌 송금은 받아 둔 계좌가 있을 때만 적을 수 있다.
   *
   * 없는 계좌로 'bank_transfer'를 기록하면 원장은 송금했다고 말하고 구매자에게는
   * "등록하신 환불계좌로 송금을 접수했습니다"가 나간다 — 존재하지 않는 계좌를
   * 근거로 한 안내다. 파기된 행(purged_at)은 통과시킨다: 수집 사실은 남아 있고,
   * 그때 송금은 실제로 그 계좌로 갔다.
   */
  if p_method = 'bank_transfer'
    and not exists (
      select 1
      from private.claim_refund_accounts as account
      where account.claim_id = p_claim_id
    )
  then
    raise exception using message = 'claim_refund_account_missing';
  end if;

  perform payment.id
  from public.payments as payment
  where payment.purpose = 'order'
    and payment.ref_id = v_claim.order_id
  order by payment.id
  for update;

  if p_stage = 'filed' then
    if v_claim.stage not in ('collected', 'processing') then
      raise exception using message = 'claim_not_refundable';
    end if;

    -- 반품은 입고가 확인된 뒤에야 durable claim이 생긴다. 그 전에 만들면
    -- 물건이 돌아오지 않은 주문의 재고가 복원 대기 상태로 열린다.
    if v_claim.stage = 'collected' then
      insert into public.order_cancellation_claims (
        order_id,
        requested_by,
        previous_status
      )
      values (v_claim.order_id, v_claim.requested_by, v_order_status)
      on conflict (order_id) do nothing;

      insert into public.refunds (
        payment_id,
        amount,
        reason,
        status,
        cancellation_request_id
      )
      select
        payment.id,
        payment.amount,
        v_claim.reason,
        case when refund.status = 'done' then 'done' else 'requested' end,
        p_claim_id
      from public.payments as payment
      left join public.refunds as refund on refund.payment_id = payment.id
      where payment.purpose = 'order'
        and payment.ref_id = v_claim.order_id
        and payment.status in ('pending', 'paid', 'canceled', 'refunded')
      on conflict (payment_id) do update
      set
        cancellation_request_id = excluded.cancellation_request_id,
        reason = coalesce(public.refunds.reason, excluded.reason),
        status = case
          when public.refunds.status = 'done' then 'done'
          else 'requested'
        end;

      update public.order_cancellation_requests
      set
        stage = 'processing',
        provider_started_at = coalesce(provider_started_at, now()),
        updated_at = now()
      where id = p_claim_id;
    end if;

    -- 수단·처리자·접수시각은 첫 기록이 이긴다. 재접수가 덮으면 이미 계좌로 송금한
    -- 건이 결제사 취소로 보이고, 실제로 접수한 사람이 마지막 클릭한 사람으로 바뀐다.
    -- 갱신 가능한 것은 상계·정산 메모뿐이다.
    update public.refunds as refund
    set
      method = coalesce(refund.method, p_method),
      handled_by = coalesce(refund.handled_by, v_actor),
      filed_at = coalesce(refund.filed_at, now()),
      settlement_note = coalesce(p_note, refund.settlement_note)
    from public.payments as payment
    where refund.payment_id = payment.id
      and payment.purpose = 'order'
      and payment.ref_id = v_claim.order_id;

    insert into public.audit_log (actor_id, action, target, diff)
    values (
      v_actor,
      'admin.order.claim_refund_filed',
      'order:' || v_claim.order_id::text,
      jsonb_build_object(
        'claimId', p_claim_id,
        'claimType', v_claim.claim_type,
        'method', p_method,
        'from', v_claim.stage,
        'to', 'processing'
      )
    );

    perform private.notify_order_claim(
      p_claim_id,
      'refund_filed',
      '환불 접수가 완료됐어요',
      case
        when p_method = 'bank_transfer'
          then '등록하신 환불계좌로 송금을 접수했습니다.'
        else '결제사에 결제 취소를 접수했습니다. 카드사 처리 일정에 따라 반영 시점이 다를 수 있습니다.'
      end
    );

    return 'filed';
  end if;

  -- 완료 기록.
  if v_claim.stage <> 'completed' then
    raise exception using message = 'claim_refund_finalization_required';
  end if;

  update public.refunds as refund
  set
    method = coalesce(refund.method, p_method),
    handled_by = coalesce(refund.handled_by, v_actor),
    completed_at = coalesce(refund.completed_at, now()),
    settlement_note = coalesce(p_note, refund.settlement_note)
  from public.payments as payment
  where refund.payment_id = payment.id
    and payment.purpose = 'order'
    and payment.ref_id = v_claim.order_id;

  get diagnostics v_refund_count = row_count;

  -- 환불 원장이 한 줄도 없는 완료는 "돈은 돌아갔는데 장부가 비었다"는 뜻이다.
  -- 첫 판매 리스크 목록이 지적한 그 상태를 여기서 막는다.
  if v_refund_count = 0 then
    raise exception using message = 'claim_refund_ledger_missing';
  end if;

  -- 환불계좌 파기 기한은 여기서 잡지 않는다. 클레임이 종결 stage에 닿는 순간
  -- private.seal_order_claim_refund_account가 이미 잡았다 — 거절·교환·레거시
  -- 완료까지 같은 규칙을 받으려면 판정이 한 곳에 있어야 한다.

  insert into public.audit_log (actor_id, action, target, diff)
  values (
    v_actor,
    'admin.order.claim_refund_completed',
    'order:' || v_claim.order_id::text,
    jsonb_build_object(
      'claimId', p_claim_id,
      'claimType', v_claim.claim_type,
      'method', p_method,
      'refundRows', v_refund_count,
      'settlementNote', p_note
    )
  );

  perform private.notify_order_claim(
    p_claim_id,
    'refund_completed',
    '환불이 완료됐어요',
    '환급 처리가 완료됐습니다. 결제수단에 따라 반영 시점이 다를 수 있습니다.'
  );

  return 'completed';
end;
$$;

revoke all on function public.admin_record_order_claim_refund(uuid, text, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.admin_record_order_claim_refund(uuid, text, text, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- 10. 교환 재출고
-- ---------------------------------------------------------------------------
-- 교환은 환불이 아니라 재출고로 종결한다. 재고 복원도 카드팩 회수도 하지 않는다 —
-- 같은 굿즈가 다시 나가므로 재고는 이미 맞고, 주문은 살아 있으므로 그 주문으로
-- 지급된 카드팩도 그대로 유효하다.
create or replace function public.admin_record_order_claim_reshipment(
  p_claim_id uuid,
  p_carrier text,
  p_tracking_number text
)
returns text
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := (select auth.uid());
  v_claim record;
  v_carrier text := nullif(btrim(coalesce(p_carrier, '')), '');
  v_tracking text := nullif(btrim(coalesce(p_tracking_number, '')), '');
begin
  if v_actor is null or not public.is_staff() then
    raise insufficient_privilege using message = 'staff required';
  end if;

  if v_carrier is null or v_tracking is null then
    raise check_violation using message = 'invalid reshipment tracking';
  end if;
  if v_tracking !~ '^[A-Z0-9]{8,30}$' then
    raise check_violation using message = 'invalid reshipment tracking';
  end if;
  -- 비활성 택배사는 새로 고를 수 없다. 기존 주문의 조회 링크는 계속 살아 있다.
  if not exists (
    select 1
    from public.shipping_carriers as carrier
    where carrier.code = v_carrier
      and carrier.is_active
  ) then
    raise check_violation using message = 'unknown shipping carrier';
  end if;

  select request.*
  into v_claim
  from public.order_cancellation_requests as request
  where request.id = p_claim_id
  for update;

  if not found then
    raise no_data_found using message = 'claim_not_found';
  end if;

  if v_claim.claim_type <> 'exchange' then
    raise exception using message = 'claim_type_has_no_reshipment';
  end if;

  if v_claim.stage = 'completed' then
    return 'completed';
  end if;

  if v_claim.stage <> 'collected' then
    raise exception using message = 'claim_not_reshippable';
  end if;

  update public.order_cancellation_requests
  set
    stage = 'completed',
    reship_carrier = v_carrier,
    reship_tracking_number = v_tracking,
    reshipped_at = now(),
    completed_at = now(),
    updated_at = now()
  where id = p_claim_id;

  insert into public.audit_log (actor_id, action, target, diff)
  values (
    v_actor,
    'admin.order.claim_reshipped',
    'order:' || v_claim.order_id::text,
    jsonb_build_object(
      'claimId', p_claim_id,
      'claimType', 'exchange',
      'from', 'collected',
      'to', 'completed',
      'carrier', v_carrier
    )
  );

  perform private.notify_order_claim(
    p_claim_id,
    'reshipped',
    '교환 상품이 재출고됐어요',
    '교환 상품을 새 운송장으로 발송했습니다.'
  );

  return 'completed';
end;
$$;

revoke all on function public.admin_record_order_claim_reshipment(uuid, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.admin_record_order_claim_reshipment(uuid, text, text)
  to authenticated;

