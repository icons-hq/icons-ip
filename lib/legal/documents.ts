export interface LegalTable {
  columns: string[];
  rows: string[][];
}

/** 조문 하나의 본문. 렌더 순서는 paragraphs → list → table → closing으로 고정한다.
 *  "다음 각 호" 뒤에 목록이 오고 그 뒤에 마무리 문장이 붙는 법정 문서의 리듬을 이 순서가 그대로 담는다. */
export interface LegalArticle {
  heading: string;
  paragraphs?: string[];
  list?: string[];
  table?: LegalTable;
  closing?: string[];
}

/** 현행 본문을 바꾸지 않고 개정 일정과 내용을 미리 알리는 사전 공지. */
export interface LegalRevisionNotice {
  announcedDate: string;
  effectiveDate: string;
  heading: string;
  changes: string[];
}

export interface LegalDocument {
  slug: LegalDocumentSlug;
  /** 문서 제목. 페이지 h1과 metadata에 함께 쓴다. */
  title: string;
  /** 푸터·온보딩처럼 좁은 자리에서 쓰는 짧은 이름. */
  navLabel: string;
  summary: string;
  effectiveDate: string;
  pendingRevision?: LegalRevisionNotice;
  articles: LegalArticle[];
}

